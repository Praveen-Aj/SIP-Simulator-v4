    public JTree addMsgTreeEntry(JTree tree, SIPScenario sipScenario) {
        String MsgText;
        ScenarioEntry.TYPE type;
        ScenarioEntry.DIRECTION direction;
        Object selection;

        if (InRadioButton.isSelected() == true) {
            direction = ScenarioEntry.DIRECTION.IN;
        } else {
            direction = ScenarioEntry.DIRECTION.OUT;
        }

        selection = SelectionComboBox.getModel().getSelectedItem();
        if (selection.toString().equals("-") == true) {
            JOptionPane.showMessageDialog(this,
                    "Please make a valid selection or type own Req/Resp",
                    "Adding entry", JOptionPane.ERROR_MESSAGE);
            return tree;
        }
        if (RequestRadioButton.isSelected() == true) {
            MsgText = selection.toString();
            type = ScenarioEntry.TYPE.REQUEST;
        } else {
            MsgText = selection.toString();
            type = ScenarioEntry.TYPE.RESPONSE;
        }
        ScenarioEntry newMsg = new SIPMessageEntry(type, direction,
                optionalCheckBox.isSelected(), MsgText);
        sipScenario.appendNewEntry(newMsg, tree);
        sipScenario.updateTreeFromScenario(tree);
        return tree;
    }
