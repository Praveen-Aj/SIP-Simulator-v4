    public JTree addMsgTreeEntry(JTree tree,
        SIPScenario sipScenario)
    {
        ScenarioEntry.TYPE type;
        ScenarioEntry newMsg;

        if (LabelButton.isSelected() == true)
        {
            type = ScenarioEntry.TYPE.LABEL;
            newMsg = new LabelEntry("label=" + LabelName.getText());
        }
        else if (GotoButton.isSelected() == true)
        {
            type = ScenarioEntry.TYPE.GOTO;
            newMsg = new GotoEntry("goto=" + GotoComboBox.getSelectedItem().toString());
        }
        else
        {
            if (VariablesComboBox.getItemCount() == 0
                || ConditionVarValue.getText().equals("") == true
                || gotoLabelComboBox.getItemCount() == 0)
            {
                JOptionPane.showMessageDialog(this,
                    "Make sure all boxes have some value",
                    "Condition validation",
                    JOptionPane.ERROR_MESSAGE);
                return tree;
            }
            newMsg = new ConditionEntry("condition=if ("
                + VariablesComboBox.getSelectedItem().toString() + " "
                + ConditionCaseBox.getSelectedItem().toString() + " "
                + ConditionVarValue.getText() + ") goto "
                + gotoLabelComboBox.getSelectedItem().toString());
        }

        sipScenario.appendNewEntry(newMsg, tree);
        sipScenario.updateTreeFromScenario(tree);
        return tree;
    }

    private void populateComboBoxWithLabels(JComboBox box)
    {
        int numEntries = sipScenario.getEntriesCount();
        LabelEntry entry;
        int cnt;
        box.removeAllItems();

        for (cnt = 0; cnt < numEntries; cnt++)
        {

            if (sipScenario.getScenarioPos(cnt).getType()
                == ScenarioEntry.TYPE.LABEL)
            {
                entry = (LabelEntry) sipScenario.getScenarioPos(cnt);
                box.addItem(new String(entry.getName()));
            }
        }
    }

    private void populateComboBoxWithVariables(JComboBox box)
    {
        int numEntries = sipScenario.getEntriesCount();
        VariableEntry entry;
        int cnt;
        box.removeAllItems();

        for (cnt = 0; cnt < numEntries; cnt++)
        {

            if (sipScenario.getScenarioPos(cnt).getType()
                == ScenarioEntry.TYPE.VARIABLE)
            {
                entry = (VariableEntry) sipScenario.getScenarioPos(cnt);
                box.addItem(new String(entry.getName()));
            }
        }
    }
