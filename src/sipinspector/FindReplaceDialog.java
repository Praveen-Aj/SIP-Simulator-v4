    private void ReplaceButtonActionPerformed(java.awt.event.ActionEvent evt)
    {
        String txtArea = textArea.getText();
        if ((txtArea = textArea.getText()).equals("") == true)
        {
            JOptionPane.showMessageDialog(this,
                "No SIP messages have been selected",
                "Find And Replace",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        String find = SearchTextField.getText();
        String replace = ReplaceTextField.getText();

        if (find.equals("") == true)
        {
            JOptionPane.showMessageDialog(this,
                "Find field needs to have some value",
                "Find And Replace",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        txtArea = txtArea.replace(find, replace);
        textArea.setText(txtArea);
        ReplaceButton.setEnabled(false);
        mainFrame.setTreeUpdateFlag();
    }

    private void CloseButtonActionPerformed(java.awt.event.ActionEvent evt)
    {
        dispose();
    }

